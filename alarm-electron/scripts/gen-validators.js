/**
 * Compiles every message schema with ajv into standalone ES module code
 * (`src/contract/schemas/validators.js`). Sandboxed renderers, the engine and
 * the shell cannot load npm packages, so they import this generated module.
 *
 *   node scripts/gen-validators.js          write the file
 *   node scripts/gen-validators.js --check  fail if the file is out of date
 */
import { readFileSync, writeFileSync } from 'node:fs'
import { fileURLToPath } from 'node:url'
import Ajv from 'ajv'
import standaloneCode from 'ajv/dist/standalone/index.js'
import { defs, messageSchemas } from '../src/contract/schemas/index.js'

const target = fileURLToPath(new URL('../src/contract/schemas/validators.js', import.meta.url))

export function generate() {
  // unicode:false → maxLength counts UTF-16 units without a runtime helper, so the code is self-contained.
  const logger = {
    log: console.log,
    warn: (/** @type {unknown[]} */ ...args) => {
      if (!String(args[0]).startsWith('DEPRECATED: option unicode')) console.warn(...args)
    },
    error: console.error,
  }
  const AjvCtor = /** @type {any} */ (Ajv).default ?? Ajv
  const ajv = new AjvCtor({ code: { source: true, esm: true, lines: false }, unicode: false, strict: true, logger })
  ajv.addSchema(defs)
  for (const s of messageSchemas) ajv.addSchema(s)
  /** @type {Record<string, string>} */
  const refs = {}
  for (const s of messageSchemas) refs[s.$id] = s.$id
  const generate = /** @type {any} */ (standaloneCode).default ?? standaloneCode
  const code = generate(ajv, refs)
  if (/require\(/.test(code)) throw new Error('Generated validators must not require runtime helpers')
  return `/* eslint-disable */\n// @ts-nocheck\n// GENERATED by scripts/gen-validators.js from src/contract — do not edit.\n${code}\n`
}

const code = generate()
if (process.argv.includes('--check')) {
  let current = ''
  try {
    current = readFileSync(target, 'utf8')
  } catch {
    // missing
  }
  if (current !== code) {
    console.error('src/contract/schemas/validators.js is out of date: run `npm run gen:validators`')
    process.exit(1)
  }
} else {
  writeFileSync(target, code)
  console.log(`wrote ${target}`)
}
